#!/usr/bin/env python3
"""Update Qord's pinned Equicord plugin inventory.

  --fetch           download the current Equibored plugins.json (or --ref), diff
                    it against the pinned copy, write docs/equicord-inventory-diff.md
  --apply           replace the pinned copy with the fetched one and regenerate
                    data/equicord/source-version.json
  --from-file PATH  use a local plugins.json instead of downloading (with --commit)

The compatibility matrix and docs/equicord-source-version.md are always
regenerated from the (possibly updated) pinned inventory.
"""

from __future__ import annotations

import argparse
import datetime as dt
import difflib
import json
import re
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import qord_inventory as inv  # noqa: E402

REPO = "Equicord/Equibored"
REPO_URL = f"https://github.com/{REPO}"
EQUICORD_URL = "https://github.com/Equicord/Equicord"
DIFF_PATH = inv.DOCS_DIR / "equicord-inventory-diff.md"
FETCH_DIR = inv.ROOT / "build" / "equicord-fetch"
COMPARED_FIELDS = ("description", "dependencies", "filePath", "commands", "target", "tags",
                   "hasPatches", "required", "enabledByDefault")


def http_get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "qord-inventory-tool",
                                               "Accept": "application/vnd.github+json"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def fetch(ref: str) -> tuple[bytes, dict]:
    meta = json.loads(http_get(f"https://api.github.com/repos/{REPO}/commits/{ref}"))
    sha = meta["sha"]
    message = meta["commit"]["message"]
    m = re.search(r"Equicord/Equicord/commit/([0-9a-f]{40})", message)
    data = http_get(f"https://raw.githubusercontent.com/{REPO}/{sha}/plugins.json")
    info = {"commit": sha, "commitDate": meta["commit"]["committer"]["date"],
            "equicordCommit": m.group(1) if m else None}
    return data, info


def similarity(a: dict, b: dict) -> float:
    path = difflib.SequenceMatcher(None, a["filePath"].lower(), b["filePath"].lower()).ratio()
    desc = difflib.SequenceMatcher(None, a["description"], b["description"]).ratio()
    return 0.5 * path + 0.5 * desc


def diff_inventories(old: list[dict], new: list[dict]) -> dict:
    old_by = {e["name"]: e for e in old}
    new_by = {e["name"]: e for e in new}
    added = sorted(set(new_by) - set(old_by))
    removed = sorted(set(old_by) - set(new_by))

    # Pair removed/added entries that look like renames: same path, or very
    # similar path + description.
    renamed = []
    for r in list(removed):
        best, best_score = None, 0.0
        for a in added:
            if old_by[r]["filePath"] == new_by[a]["filePath"]:
                best, best_score = a, 1.0
                break
            score = similarity(old_by[r], new_by[a])
            if score > best_score:
                best, best_score = a, score
        if best is not None and best_score >= 0.75:
            renamed.append((r, best, round(best_score, 2)))
            removed.remove(r)
            added.remove(best)

    changed = []
    for name in sorted(set(old_by) & set(new_by)):
        for f in COMPARED_FIELDS:
            if old_by[name].get(f) != new_by[name].get(f):
                changed.append((name, f, old_by[name].get(f), new_by[name].get(f)))
    for old_name, new_name, _ in renamed:
        for f in COMPARED_FIELDS:
            if old_by[old_name].get(f) != new_by[new_name].get(f):
                changed.append((f"{old_name} -> {new_name}", f, old_by[old_name].get(f), new_by[new_name].get(f)))
    return {"added": added, "removed": removed, "renamed": renamed, "changed": changed,
            "old_count": len(old), "new_count": len(new), "new_by": new_by}


def render_diff(d: dict, old_sv: dict, new_info: dict) -> str:
    def fmt(v):
        return "`" + json.dumps(v, ensure_ascii=False).replace("|", "\\|") + "`"

    lines = [
        "# Equicord inventory diff",
        "",
        "<!-- Generated by tools/update_equicord_inventory.py --fetch. Do not edit. -->",
        "",
        f"Pinned: `{old_sv.get('commit')}` ({d['old_count']} plugins)  ",
        f"Fetched: `{new_info.get('commit')}` ({d['new_count']} plugins), Equicord `{new_info.get('equicordCommit')}`",
        "",
        f"## New plugins ({len(d['added'])})",
        "",
    ]
    lines += [f"- **{n}** `{d['new_by'][n]['filePath']}`: {d['new_by'][n]['description']}" for n in d["added"]] or ["None."]
    lines += ["", f"## Removed plugins ({len(d['removed'])})", ""]
    lines += [f"- **{n}**" for n in d["removed"]] or ["None."]
    lines += ["", f"## Renamed plugins ({len(d['renamed'])})", ""]
    lines += [f"- **{a}** -> **{b}** (similarity {s})" for a, b, s in d["renamed"]] or ["None."]
    lines += ["", f"## Changed fields ({len(d['changed'])})", ""]
    if d["changed"]:
        lines += ["| Plugin | Field | Old | New |", "|---|---|---|---|"]
        lines += [f"| {n} | {f} | {fmt(o)} | {fmt(nv)} |" for n, f, o, nv in d["changed"]]
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def write_source_version(data: bytes, info: dict) -> None:
    sv = {
        "repository": REPO_URL,
        "commit": info["commit"],
        "commitDate": info.get("commitDate"),
        "equicordRepository": EQUICORD_URL,
        "equicordCommit": info.get("equicordCommit"),
        "file": "plugins.json",
        "sha256": __import__("hashlib").sha256(data).hexdigest(),
        "importedAt": dt.date.today().isoformat(),
    }
    inv.SOURCE_VERSION_PATH.write_text(json.dumps(sv, indent=2) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fetch", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--ref", default="main", help="Equibored branch or commit to fetch (default: main)")
    ap.add_argument("--from-file", type=Path, help="local plugins.json to use instead of downloading")
    ap.add_argument("--commit", help="Equibored commit the --from-file copy comes from")
    ap.add_argument("--commit-date", help="date of that commit (ISO 8601)")
    ap.add_argument("--equicord-commit", help="Equicord commit referenced by that Equibored commit")
    args = ap.parse_args()

    if args.apply and not (args.fetch or args.from_file):
        ap.error("--apply needs --fetch or --from-file")
    if args.from_file and not args.commit:
        ap.error("--from-file needs --commit")

    new_data = None
    if args.from_file:
        new_data = args.from_file.read_bytes()
        info = {"commit": args.commit, "commitDate": args.commit_date, "equicordCommit": args.equicord_commit}
    elif args.fetch:
        new_data, info = fetch(args.ref)
        FETCH_DIR.mkdir(parents=True, exist_ok=True)
        (FETCH_DIR / "plugins.json").write_bytes(new_data)
        (FETCH_DIR / "info.json").write_text(json.dumps(info, indent=2), encoding="utf-8")

    if new_data is not None:
        new_entries = json.loads(new_data)
        problems = inv.validate_inventory(new_entries)
        if problems:
            for p in problems:
                print(p, file=sys.stderr)
            return 1
        old_entries = inv.load_json(inv.INVENTORY_PATH) if inv.INVENTORY_PATH.is_file() else []
        old_sv = inv.load_json(inv.SOURCE_VERSION_PATH) if inv.SOURCE_VERSION_PATH.is_file() else {}
        d = diff_inventories(old_entries, new_entries)
        inv.DOCS_DIR.mkdir(exist_ok=True)
        DIFF_PATH.write_text(render_diff(d, old_sv, info), encoding="utf-8", newline="\n")
        print(f"{len(d['added'])} new, {len(d['removed'])} removed, {len(d['renamed'])} renamed, "
              f"{len(d['changed'])} field changes -> {DIFF_PATH.relative_to(inv.ROOT).as_posix()}")
        if args.apply:
            inv.DATA_DIR.mkdir(parents=True, exist_ok=True)
            inv.INVENTORY_PATH.write_bytes(new_data)
            write_source_version(new_data, info)
            print(f"applied inventory {info['commit']}")

    records, errors, _warnings, ctx = inv.evaluate()
    for p in inv.write_docs(records, ctx):
        print(f"wrote {p.relative_to(inv.ROOT).as_posix()}")
    if errors:
        print(f"{len(errors)} integrity error(s); run tools/check_equicord_plugins.py for details", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
